#!/usr/bin/env node
// Renders one Markdown page per layout or component into docs/, in the front
// matter shape foundationcss.com consumes. Only files carrying GENERATED_MARK
// are ever deleted; hand-written guides are never touched.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { frontMatter } from './lib/front-matter.js';
import { loadSchema, loadAndMerge, loadVocabulary, KIND_TO_DIR } from './lib/manifest.js';
import { formatError } from './validate.js';
import { declaredTokens, loadCatalogue } from './lib/tokens.js';
import { walkFiles } from './lib/files.js';
import { stripComments } from './lib/imports.js';

export const GENERATED_MARK = '<!-- Generated by bin/gen-docs.js';
// The nav groups a reader browses by. A manifest names its own; the kind is
// the fallback, so a component added without one still lands somewhere. The
// order here is the order the docs site shows them: arrange the page, fill it,
// let people move around it, let them act, tell them what happened.
const GROUPS = { layout: 'Layouts', recipe: 'Recipes', component: 'Components', utility: 'Utilities' };
// Motion comes after Feedback and before Reference: it is the last thing a
// page gets, once it is arranged, filled, navigable and answering back.
export const NAV_GROUPS = ['Guides', 'Page Layouts', 'Grids and Rows', 'Boxes and Stacks', 'Content', 'Navigation', 'Forms and Actions', 'Feedback', 'Motion', 'Reference'];
const groupOf = (m) => m.group ?? GROUPS[m.kind];
const RESERVED_PAGES = new Set(['tokens']);

// The tokens page's headings, in order, are the catalogue schema's own group
// enum: a group added there can never be missed by a hard-coded list here.
export const tokenGroups = (schema) => schema.items.properties.group.enum;
const SCHEMA_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'schema');
const TOKEN_GROUPS = tokenGroups(loadSchema(path.join(SCHEMA_DIR, 'tokens.schema.json')));

const titleCase = (name) => name.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');
const cell = (v) => String(v ?? '').replace(/\|/g, '\\|');
const code = (v) => `\`${v}\``;
// Every table on a reference page goes in a scroller, because most of a
// reference page is table and the widest of them do not fit a phone. The
// scroller's own manifest names this case: one wide item, which the track then
// gives horizontal overflow. Without it a table simply runs off the side of
// the page, and there is nothing CSS alone can do about it — a Markdown table
// has no wrapper to scroll inside, and making the table itself a block box
// takes its role away from a screen reader.
//
// markdown="1" and the blank lines are both load-bearing, and for different
// readers. PHP Markdown Extra, which renders the docs site, leaves the table
// as literal pipes without the attribute; GitHub ignores the attribute but
// needs the blank lines, and without them leaves the pipes just the same.
// Together they render as a table in both, which is checked, and GitHub drops
// the class and the attribute from its output as it always does.
// label names the track for a screen reader; a scrollable region has to carry
// a name, a role and a tab stop, and validate-html enforces all three.
const table = (label, headers, rows) => [
	`<div class="scroller" role="region" aria-label="${escapeAttribute(label)}" tabindex="0" markdown="1">`,
	'',
	`| ${headers.join(' | ')} |`,
	`| ${headers.map(() => '---').join(' | ')} |`,
	...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
	'',
	'</div>',
].join('\n');

/** Escapes text for an HTML attribute value; the five characters that can end or break one. */
export function escapeAttribute(text) {
	return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// The example twice: framed, so it renders live with only Yeti's stylesheet
// inside; and fenced, so a renderer that strips iframes, GitHub among them,
// still shows the code. The blank lines are load-bearing: a raw HTML block
// in Markdown ends at one, and the fence needs to be parsed as Markdown.
// markdown="1" is for PHP Markdown Extra, the docs site's engine, which
// otherwise swallows everything up to </details> as one raw block and leaves
// the fence as literal text; GitHub ignores the unknown attribute and parses
// the fence anyway, because the blank lines already ended its HTML block.
// The framed box takes no tabindex: the iframe fills it exactly, so it never
// scrolls, and a tab stop there would stop the reader for nothing.
// The srcdoc value's newlines are encoded, because an attribute cannot span
// the blank line inside an example without ending CommonMark's HTML block;
// the browser decodes them back before parsing the framed document. A <base>
// ahead of everything else points relative example URLs — images, above all —
// at the stylesheet's own folder, since a srcdoc frame otherwise resolves
// them against the docs page.
export function renderDemo({ title, exampleHtml, stylesheet, height = 'lg', width, resize }) {
	// More than one stylesheet is allowed, and is how a themed host should do
	// it: the page has already fetched yeti.css, so naming that same URL first
	// and a small theme after it costs the frame one short file rather than a
	// second copy of the framework. The first one places the base and the
	// module bundle beside it.
	const sheets = Array.isArray(stylesheet) ? stylesheet : [stylesheet];
	const base = `${path.posix.dirname(sheets[0])}/`.replace(/\/+$/, '/');
	const links = sheets.map((href) => `<link rel="stylesheet" href="${href}">`).join('');
	// The frame is a whole Yeti page: the stylesheets and, beside the first,
	// the bundle of every module, so a framed dialog opens, framed tabs switch,
	// and an example that composes components gets all of their scripts.
	// An example's placeholder links are written href="#", which in an ordinary
	// page goes nowhere. Here it does: the base above is what makes a relative
	// picture resolve, and it also makes "#" resolve against that base rather
	// than against the frame, whose own URL is about:srcdoc. Clicking a nav item
	// would load the whole docs page inside the demo. This cancels a click on a
	// link that was only ever a placeholder, and leaves every real href alone.
	const inert = '<script>addEventListener("click",function(e){var a=e.target.closest&&e.target.closest(\'a[href="#"]\');if(a)e.preventDefault();});</script>';
	const doc = `<base href="${base}">${links}<script type="module" src="${base}yeti.js"></script>${inert}<body style="margin:0;padding:var(--yeti-space-md)">${exampleHtml.trim()}`;
	const srcdoc = escapeAttribute(doc).replace(/\r?\n/g, '&#10;');
	return [
		`<figure class="demo" data-height="${height}"${width ? ` data-width="${width}"` : ''}${resize ? ` data-resize="${resize}"` : ''}>`,
		`<div data-preview="${escapeAttribute(title)}"><iframe title="${escapeAttribute(title)}, live" srcdoc="${srcdoc}"></iframe></div>`,
		'',
		'<details markdown="1">',
		'<summary>View Code</summary>',
		'',
		'```html',
		exampleHtml.trim(),
		'```',
		'',
		'</details>',
		'</figure>',
	].join('\n');
}

function range(child) {
	const min = child.min ?? 0;
	const max = child.max ?? null;
	if (max === null) return min === 0 ? 'any number' : `at least ${min}`;
	if (min === max) return `exactly ${min}`;
	return `${min} to ${max}`;
}

export function renderPage({ manifest: m, exampleHtml, navOrder, docsMd = '', demoStylesheet = '/yeti/yeti.css' }) {
	const title = titleCase(m.name);
	const dir = KIND_TO_DIR[m.kind];
	const out = [];

	// trimEnd so the join below adds exactly one newline before the generated mark
	out.push(frontMatter({ raw: true, title, description: m.description, nav_group: groupOf(m), nav_order: navOrder }).trimEnd());
	// The description is the page's lede, and says so with a class rather than
	// by being the paragraph after the heading: a host that wraps the two in a
	// layout would otherwise lose it silently.
	out.push(`${GENERATED_MARK} from src/${dir}/${m.name}/manifest.json. Do not edit. -->`, '', `# ${title}`, '', `<p class="lede">${m.description}</p>`, '');

	out.push('## Example', '', renderDemo({ title, exampleHtml, stylesheet: demoStylesheet, height: m.demo?.height, width: m.demo?.width, resize: m.demo?.resize }), '');
	if (docsMd.trim()) out.push(docsMd.trim(), '');

	out.push('## Attributes', '');
	out.push(m.attributes.length
		? table(`${title} attributes`, ['Attribute', 'Type', 'Values', 'Default', 'Description'], m.attributes.map((a) => [
			code(a.name), a.type, (a.values ?? []).map(code).join(', '), a.default === undefined ? '' : code(a.default), a.description,
		]))
		: 'None. This is configured through its children and tokens only.');
	out.push('');

	if ((m.markers ?? []).length) {
		out.push('## Markers', '', 'Attributes that descendants carry, not the root.', '');
		out.push(table(`${title} markers`, ['Attribute', 'Type', 'Values', 'On', 'Description'], m.markers.map((k) => [
			code(k.name), k.type, (k.values ?? []).map(code).join(', '), k.on ? code(k.on) : '', k.description,
		])), '');
	}

	if (m.classes.length) {
		out.push('## Modifier classes', '', table(`${title} modifier classes`, ['Class', 'Description'], m.classes.map((c) => [code(`.${c.name}`), c.description])), '');
	}

	out.push('## Children', '');
	out.push(m.children.length
		? m.children.map((c) => `- ${code(c.selector)}: ${range(c)}${c.description ? `. ${c.description}` : ''}`).join('\n')
		: 'No structural requirements.');
	out.push('');

	const publicTokens = m.tokens.filter((t) => t.public);
	const internalTokens = m.tokens.filter((t) => !t.public);
	out.push('## Tokens', '');
	out.push(publicTokens.length ? table(`${title} tokens`, ['Token', 'Description'], publicTokens.map((t) => [code(t.name), t.description ?? ''])) : 'No public tokens.');
	if (internalTokens.length) {
		out.push('', '<details><summary>Internal tokens (may change between minor versions)</summary>', '', internalTokens.map((t) => `- ${code(t.name)}`).join('\n'), '', '</details>');
	}
	out.push('');

	out.push('## Accessibility', '');
	const a11y = [];
	if (m.a11y.role) a11y.push(`- Role: ${code(m.a11y.role)}`);
	// "aria-label | aria-labelledby" is an alternation: any one of them satisfies it.
	const required = (r) => r.split('|').map((o) => code(o.trim())).join(' or ');
	if (m.a11y.requiredAttributes.length) a11y.push(`- Required attributes: ${m.a11y.requiredAttributes.map(required).join(', ')}`);
	if (m.a11y.notes) a11y.push(`- ${m.a11y.notes}`);
	out.push(a11y.length ? a11y.join('\n') : 'No special requirements beyond semantic HTML.');
	if (m.a11y.keyboard.length) out.push('', table(`${title} keyboard shortcuts`, ['Key', 'Action'], m.a11y.keyboard.map((k) => [code(k.key), k.action])));
	out.push('');

	out.push('## Browser support', '');
	out.push(`- Used without guards: ${m.support.unguarded.length ? m.support.unguarded.join(', ') : 'nothing beyond the Baseline 2025 floor'}`);
	out.push(`- Behind ${code('@supports')}: ${m.support.guarded.length ? m.support.guarded.join(', ') : 'nothing'}`);
	out.push('');

	out.push('## JavaScript', '');
	// A component may ship more than one module, each loaded on its own; the
	// events come after the list because they are the contract between the
	// modules and a page's own script, not a property of any one file.
	const modules = m.js ?? [];
	if (!modules.length) {
		out.push('None. This component is CSS only.');
	} else {
		out.push(modules.map((mod) => `Optional enhancement: ${code(`${dir}/${m.name}/${mod.module}`)}. The component works without it.`).join('\n\n'));
		const events = modules.flatMap((mod) => (mod.events ?? []).map((e) => [e, mod]));
		if (events.length) {
			out.push('', 'Each event bubbles, crosses a shadow boundary, and cannot be cancelled.', '');
			out.push(table(`${title} events`, ['Event', 'Module', 'Detail', 'Description'], events.map(([e, mod]) => [
				code(e.name), code(mod.module), e.detail ? code(e.detail) : 'none', e.description,
			])));
		}
	}
	out.push('', `Available since ${m.since}.`, '');

	return out.join('\n');
}

export function renderTokensPage(entries, internalCount, groups = TOKEN_GROUPS) {
	const out = [];
	out.push(frontMatter({ raw: true, title: 'Tokens', description: 'Every public Yeti custom property, grouped, with its default and what it is for.', nav_group: 'Reference', nav_order: 1 }).trimEnd());
	out.push(`${GENERATED_MARK} from src/tokens/tokens.json. Do not edit. -->`, '', '# Tokens', '');
	out.push('Public tokens are the theming API: set them in your own stylesheet and everything that reads them follows. Names are `--yeti-<group>-<name>`. Sizes use `xs sm md lg xl 2xl 3xl`, where `md` is the base step.', '');
	for (const group of groups) {
		const rows = entries.filter((e) => e.group === group);
		if (!rows.length) continue;
		out.push(`## ${group[0].toUpperCase()}${group.slice(1)}`, '');
		out.push(table(`${group[0].toUpperCase()}${group.slice(1)} tokens`, ['Token', 'Default', 'Description'], rows.map((e) => [
			code(e.name), e.declared === false ? `${e.default} (override only)` : code(e.default), e.description,
		])), '');
	}
	out.push(`Yeti also defines ${internalCount} internal \`--_yeti-*\` tokens. They derive from the public ones and may change between minor versions; override the public token instead.`, '');
	return out.join('\n');
}

// The two guides each carry a table of every attribute their kinds declare.
// The rows come from the manifests, so a new attribute reaches the guide the
// moment it validates and a rename can never leave the guide behind. Only
// what is between the markers is generated; the prose around them is written
// by hand and never touched.
export const ATTRIBUTES_START = '<!-- yeti:attributes:start -->';
export const ATTRIBUTES_END = '<!-- yeti:attributes:end -->';
export const GUIDE_TABLES = [
	{ file: 'guides/layouts.md', kinds: ['layout', 'recipe'], label: 'Layout attributes' },
	{ file: 'guides/components.md', kinds: ['component', 'utility'], label: 'Component attributes' },
];

/** One row per attribute of the given kinds: its values, and every component that reads it. */
export function renderAttributeTable({ merged, kinds, label }) {
	const rows = new Map();
	const add = (attr, reader) => {
		const row = rows.get(attr.name) ?? { attr, readers: [] };
		row.readers.push(reader);
		rows.set(attr.name, row);
	};
	for (const name of Object.keys(merged).sort()) {
		const m = merged[name];
		if (!kinds.includes(m.kind)) continue;
		for (const attr of m.attributes) add(attr, name);
		// A marker is carried by a descendant, so the reader names the element
		// it goes on. The parentheses matter: a selector such as "td, th" has a
		// comma of its own, and the readers are comma-separated.
		for (const marker of m.markers ?? []) add(marker, `${name} (${marker.on ?? 'a descendant'})`);
	}
	return table(label, ['Attribute', 'Values', 'Read by'], [...rows.keys()].sort().map((name) => {
		const { attr, readers } = rows.get(name);
		return [code(name), attr.type === 'enum' ? attr.values.map(code).join(', ') : attr.type, readers.join(', ')];
	}));
}

/** The markdown with `block` between the markers, or null when the file has no usable pair. */
export function replaceMarked(markdown, block) {
	const start = markdown.indexOf(ATTRIBUTES_START);
	const end = markdown.indexOf(ATTRIBUTES_END);
	if (start === -1 || end === -1 || end < start) return null;
	return `${markdown.slice(0, start + ATTRIBUTES_START.length)}\n\n${block}\n\n${markdown.slice(end)}`;
}

function countInternalTokens(tokensDir) {
	const names = new Set();
	for (const file of walkFiles(tokensDir).filter((f) => f.endsWith('.css'))) {
		const css = stripComments(fs.readFileSync(file, 'utf8'));
		for (const m of css.matchAll(/(--_yeti-[a-z0-9-]+)\s*:/g)) names.add(m[1]);
	}
	return names.size;
}

// outDir is where the pages land, and defaults to this repo's own docs/. A
// host that themes Yeti passes its own: foundationcss.com generates the pages
// it serves straight into its src/pages/yeti/, with demo frames pointing at
// its themed, cache-stamped stylesheet. That used to be done by generating
// over docs/ here and restoring it afterwards, which left the stamped pages in
// this repo whenever the import did not reach its last line.
export function generateDocs({ root, demoStylesheet, outDir }) {
	const srcDir = path.join(root, 'src');
	const docsDir = outDir ? path.resolve(outDir) : path.join(root, 'docs');
	const schema = loadSchema(path.join(root, 'schema', 'manifest.schema.json'));
	const vocabFile = path.join(root, 'schema', 'vocabulary.json');
	const vocabulary = fs.existsSync(vocabFile) ? loadVocabulary(vocabFile) : {};
	const { entries, merged, errors } = loadAndMerge(srcDir, schema, vocabulary);
	if (errors.length) return { written: [], deleted: [], errors };

	const catalogueFile = path.join(srcDir, 'tokens', 'tokens.json');
	let tokenEntries = null;
	let tokenGroupOrder = TOKEN_GROUPS;
	if (fs.existsSync(catalogueFile)) {
		const tokensSchema = loadSchema(path.join(root, 'schema', 'tokens.schema.json'));
		const loaded = loadCatalogue(catalogueFile, tokensSchema);
		if (loaded.errors.length) return { written: [], deleted: [], errors: loaded.errors };
		tokenEntries = loaded.entries;
		tokenGroupOrder = tokenGroups(tokensSchema);
	}

	const clobberErrors = [];
	for (const entry of entries) {
		const file = path.join(docsDir, `${entry.name}.md`);
		if (fs.existsSync(file) && !isGenerated(fs.readFileSync(file, 'utf8'))) {
			clobberErrors.push({ file, message: 'refusing to overwrite a hand-written page; rename it or remove the component' });
		}
	}
	if (tokenEntries !== null) {
		const file = path.join(docsDir, 'tokens.md');
		if (fs.existsSync(file) && !isGenerated(fs.readFileSync(file, 'utf8'))) {
			clobberErrors.push({ file, message: 'refusing to overwrite a hand-written docs/tokens.md; rename it so the generated tokens page can be written' });
		}
	}
	if (clobberErrors.length) return { written: [], deleted: [], errors: clobberErrors };

	fs.mkdirSync(docsDir, { recursive: true });
	const written = [];
	// Ordered within the nav group, not the kind, or two pages in one group
	// would each think they were first.
	const byGroup = {};
	for (const entry of entries) (byGroup[groupOf(entry.manifest)] ??= []).push(entry);
	for (const group of Object.values(byGroup)) {
		group.sort((a, b) => a.name.localeCompare(b.name));
		group.forEach((entry, i) => {
			const exampleHtml = fs.readFileSync(path.join(entry.dir, 'example.html'), 'utf8');
			const docsMdFile = path.join(entry.dir, 'docs.md');
			const docsMd = fs.existsSync(docsMdFile) ? fs.readFileSync(docsMdFile, 'utf8') : '';
			const file = path.join(docsDir, `${entry.name}.md`);
			fs.writeFileSync(file, renderPage({ manifest: entry.manifest, exampleHtml, navOrder: i + 1, docsMd, demoStylesheet }));
			written.push(file);
		});
	}

	if (tokenEntries !== null) {
		const file = path.join(docsDir, 'tokens.md');
		fs.writeFileSync(file, renderTokensPage(tokenEntries, countInternalTokens(path.join(srcDir, 'tokens')), tokenGroupOrder));
		written.push(file);
	}

	const deleted = [];
	for (const name of fs.readdirSync(docsDir)) {
		if (!name.endsWith('.md')) continue;
		const file = path.join(docsDir, name);
		if (!fs.statSync(file).isFile()) continue;
		const base = name.slice(0, -3);
		const reserved = RESERVED_PAGES.has(base) && tokenEntries !== null;
		if (isGenerated(fs.readFileSync(file, 'utf8')) && !(base in merged) && !reserved) {
			fs.unlinkSync(file);
			deleted.push(file);
		}
	}
	// The guides are hand-written pages with one generated table in each, so
	// they are written last and only between their markers. A host generating
	// into its own tree may not have them; that is not an error.
	const guideErrors = [];
	for (const { file, kinds, label } of GUIDE_TABLES) {
		const guide = path.join(docsDir, file);
		if (!fs.existsSync(guide)) continue;
		const markdown = fs.readFileSync(guide, 'utf8');
		const next = replaceMarked(markdown, renderAttributeTable({ merged, kinds, label }));
		if (next === null) {
			guideErrors.push({ file: guide, message: `no ${ATTRIBUTES_START} … ${ATTRIBUTES_END} pair for the generated attribute table` });
			continue;
		}
		if (next !== markdown) fs.writeFileSync(guide, next);
		written.push(guide);
	}
	return { written, deleted, errors: guideErrors };
}

/** True only when the generated mark is the first thing after the front matter block. */
export function isGenerated(content) {
	const m = content.match(/^---\n[\s\S]*?\n---\n/);
	if (!m) return false;
	return content.slice(m[0].length).trimStart().startsWith(GENERATED_MARK);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
	const root = process.cwd();
	// A host that themes Yeti wants its own stylesheet inside the demo frames,
	// so foundationcss.com can point them at its themed build rather than the
	// framework's defaults. Absent, the frames load the site's plain yeti.css.
	const flag = process.argv.indexOf('--stylesheet');
	// Comma-separated, so a themed host can name the framework and its theme.
	const demoStylesheet = flag === -1 ? undefined : process.argv[flag + 1]?.split(',').map((s) => s.trim()).filter(Boolean);
	// Where the pages are written; docs/ when absent. A themed host generates
	// into its own tree rather than over this one.
	const outFlag = process.argv.indexOf('--out');
	const outDir = outFlag === -1 ? undefined : process.argv[outFlag + 1];
	if ((flag !== -1 && !demoStylesheet?.length) || (outFlag !== -1 && !outDir)) {
		console.error('usage: node bin/gen-docs.js [--stylesheet <path>] [--out <dir>]');
		process.exit(2);
	}
	const { written, deleted, errors } = generateDocs({ root, demoStylesheet, outDir });
	for (const e of errors) console.error(formatError(root, e));
	if (errors.length) {
		console.error('docs: aborted');
		process.exit(1);
	}
	console.log(`docs: wrote ${written.length}, removed ${deleted.length}`);
}
